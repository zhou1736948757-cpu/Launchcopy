/// App-owned modal and retained save-notice vocabulary; user data remains literal.
public enum NoticeTextKey: String, CaseIterable, Sendable {
    case okay = "notice.okay"
    case save = "notice.save"
    case aliasEditorTitle = "notice.aliasEditorTitle"
    case aliasEditorHelp = "notice.aliasEditorHelp"
    case aliasEditorAccessibility = "notice.aliasEditorAccessibility"
    case organizationErrorTitle = "notice.organizationErrorTitle"
    case organizationErrorHelp = "notice.organizationErrorHelp"
    case managementErrorTitle = "notice.managementErrorTitle"
    case aliasInvalidMessage = "notice.aliasInvalidMessage"
    case managementFutureMessage = "notice.managementFutureMessage"
    case managementFailedMessage = "notice.managementFailedMessage"
    case workspaceSaveAccessibility = "notice.workspaceSaveAccessibility"
    case workspaceUnsavedMessage = "notice.workspaceUnsavedMessage"
    case quitSaveTitle = "notice.quitSaveTitle"
    case quitSaveMessage = "notice.quitSaveMessage"
    case cancelQuit = "notice.cancelQuit"
    case quitAnyway = "notice.quitAnyway"
    case workspaceProtectedMessage = "notice.workspaceProtectedMessage"
    case workspaceStaleMessage = "notice.workspaceStaleMessage"
    case workspaceLimitMessage = "notice.workspaceLimitMessage"
    case workspaceTimedOutMessage = "notice.workspaceTimedOutMessage"

    public var englishFallback: String {
        switch self {
        case .workspaceProtectedMessage: return "The layout is protected and could not be saved. The current arrangement remains in memory; existing saved data was not overwritten."
        case .workspaceStaleMessage: return "The save was rejected because the layout changed. The current arrangement remains in memory; newer saved data was not overwritten."
        case .workspaceLimitMessage: return "The layout exceeds the supported save limits. The current arrangement remains in memory; existing saved data was not overwritten."
        case .workspaceTimedOutMessage: return "Saving did not finish in time. The current arrangement remains in memory. Wait and retry before quitting."
        case .okay: return "OK"
        case .save: return "Save"
        case .aliasEditorTitle: return "Set App Alias"
        case .aliasEditorHelp: return "Aliases affect only display and search. Leave empty to restore the original name. Use at most 128 characters, without control characters."
        case .aliasEditorAccessibility: return "App alias"
        case .organizationErrorTitle: return "Could Not Organize App"
        case .organizationErrorHelp: return "The app or layout changed, or the layout is protected. Reopen the menu and try again."
        case .managementErrorTitle: return "App Management Settings Were Not Saved"
        case .aliasInvalidMessage: return "Aliases cannot contain control characters and must be 128 characters or fewer. Edit the alias and try again."
        case .managementFutureMessage: return "These settings were saved by a newer version and will not be overwritten."
        case .managementFailedMessage: return "The app may have changed or the settings could not be saved. Select the app again and retry."
        case .workspaceSaveAccessibility: return "Layout save status"
        case .workspaceUnsavedMessage: return "The layout is not saved yet. The current arrangement remains in memory. Retry or check available disk space."
        case .quitSaveTitle: return "Changes Not Saved"
        case .quitSaveMessage: return "Some changes could not be saved before quitting. Quitting now may lose recent changes. Cancel and retry, or quit without saving."
        case .cancelQuit: return "Cancel Quit"
        case .quitAnyway: return "Quit Anyway"
        }
    }
}
