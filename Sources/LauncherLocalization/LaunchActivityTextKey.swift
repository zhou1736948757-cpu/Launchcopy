/// Static presentation copy for optional, local Launchcopy launch-request history.
public enum LaunchActivityTextKey: String, CaseIterable, Sendable {
    case title = "launchActivity.title"
    case enabled = "launchActivity.enabled"
    case privacyHelp = "launchActivity.privacyHelp"
    case recent = "launchActivity.recent"
    case frequent = "launchActivity.frequent"
    case emptyRecent = "launchActivity.emptyRecent"
    case emptyFrequent = "launchActivity.emptyFrequent"
    case off = "launchActivity.off"
    case saving = "launchActivity.saving"
    case saved = "launchActivity.saved"
    case saveFailed = "launchActivity.saveFailed"
    case unavailable = "launchActivity.unavailable"
    case protected = "launchActivity.protected"
    case recoveryRequired = "launchActivity.recoveryRequired"
    case recover = "launchActivity.recover"
    case clear = "launchActivity.clear"
    case clearTitle = "launchActivity.clearTitle"
    case clearMessage = "launchActivity.clearMessage"
    case clearConfirm = "launchActivity.clearConfirm"
    case cancel = "launchActivity.cancel"
    case cleared = "launchActivity.cleared"
    case retry = "launchActivity.retry"
    case waiting = "launchActivity.waiting"
    case libraryDisabled = "launchActivity.libraryDisabled"

    /// Last-resort text when selected-language and English resources are unavailable.
    public var englishFallback: String {
        switch self {
        case .title: return "Recent and Frequent"
        case .enabled: return "Remember Launchcopy launch requests"
        case .privacyHelp: return "Off by default. Records only app identities and launch-request times/counts for requests made through Launchcopy and accepted by its launch executor. Recent and Frequent cover a rolling 30-day window (UTC days). Data is stored only on this Mac; no monitoring of other apps or activity and no uploads. Acceptance does not prove that an app opened or was used. Turning this off or disabling App Library stops recording and hides Recent and Frequent without erasing retained data. Disabling App Library also turns this recording switch off; turn recording on explicitly to resume. Use Clear History to remove it explicitly."
        case .recent: return "Recent"
        case .frequent: return "Frequent"
        case .emptyRecent: return "No accepted Launchcopy launch requests to show in Recent."
        case .emptyFrequent: return "No apps from accepted Launchcopy launch requests to show in Frequent for the last 30 days."
        case .off: return "Recording is off. Recent and Frequent are hidden. Retained data is not erased; use Clear History to remove it."
        case .saving: return "Saving launch history changes…"
        case .saved: return "Launch history changes saved."
        case .saveFailed: return "Could not save launch history changes. Choose Retry Saving to try again. App launch results are separate."
        case .unavailable: return "Launch history is unavailable. Recording is paused; stored data will not be overwritten."
        case .protected: return "Saved launch history uses a newer or unrecognized format and is protected. Recording is paused; stored data will not be overwritten."
        case .recoveryRequired: return "Saved launch history is damaged. Recording is paused. Choose Recover Launch History… to review recovery."
        case .recover: return "Recover Launch History…"
        case .clear: return "Clear History…"
        case .clearTitle: return "Clear Launch History?"
        case .clearMessage: return "Permanently delete only the Recent and Frequent launch-request records saved by Launchcopy. This cannot be undone. App Library categories, aliases, hidden apps, app arrangement and other settings stay unchanged. Clearing history does not turn recording on."
        case .clearConfirm: return "Delete Launch History"
        case .cancel: return "Cancel"
        case .cleared: return "Recent and Frequent launch history cleared. Recording has not been turned on by this action."
        case .retry: return "Retry Saving"
        case .waiting: return "Waiting for launch history to become ready…"
        case .libraryDisabled: return "App Library is off. Recording is stopped and Recent and Frequent are hidden. Retained data is not erased; use Clear History to remove it."
        }
    }
}
